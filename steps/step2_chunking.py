"""2단계: 청킹 — 긴 문서를 검색 단위로 자르기

1단계에서는 짧은 문장 5개를 다뤘습니다. 그런데 실제 문서는 깁니다.
문서 하나를 통째로 벡터 하나로 만들면 두 가지가 망가집니다.

  1) 검색이 뭉개진다
     '휴가정책.md' 한 장에 연차·병가·경조사·휴직이 다 들어 있으면,
     그 벡터는 "휴가 관련 이것저것"이라는 흐릿한 평균이 됩니다.
     "연차 며칠?" 로 찾아도 정확히 걸리지 않습니다.

  2) LLM 에 넘길 게 너무 많다
     답이 두 줄인데 문서 전체를 보내면 비싸고 느리고 부정확합니다.

그래서 **의미가 하나로 묶이는 덩어리**로 잘라둡니다. 이 덩어리를 청크(chunk)라고 합니다.

이 단계는 모델을 안 쓰기 때문에 실행이 즉시 끝납니다. 마음껏 실험해보세요.

실행:
    python steps/step2_chunking.py
"""

from pathlib import Path

# 이 파일(steps/step2_chunking.py)의 부모의 부모 = 저장소 루트
ROOT = Path(__file__).resolve().parent.parent
DOC_PATH = ROOT / "data" / "docs" / "01-휴가정책.md"


# ===========================================================================
# TODO 1. 문서 파일을 읽어서 문자열로 만드세요.
#
#   DOC_PATH 는 Path 라는 "경로 객체"입니다. 이 객체에게 읽어달라고 시킵니다.
#
#       경로객체.read_text(encoding="utf-8")
#
#   encoding="utf-8" 은 "이 파일은 UTF-8 로 저장돼 있다"고 알려주는 것입니다.
#   Windows 에서 한글 파일을 읽을 때 이걸 빼먹으면 글자가 깨집니다.
# ===========================================================================

raw = DOC_PATH.read_text(encoding="utf-8")  # ← 여기를 채우세요


# ===========================================================================
# TODO 2. 문서를 "## " 제목 기준으로 잘라 sections 리스트를 만드세요.
#
#   문서를 열어보면 이렇게 생겼습니다:
#
#       # 누리테크 휴가 정책
#
#       ## 연차 휴가
#       정규직 구성원은 ...
#
#       ## 병가
#       병가는 연 10일까지 ...
#
#   문자열에는 split 이라는 기능이 있습니다. 기준 글자로 잘라 리스트를 만듭니다.
#
#       "a-b-c".split("-")        →  ["a", "b", "c"]
#       "사과,포도".split(",")     →  ["사과", "포도"]
#
#   우리는 "\n## " 를 기준으로 자르면 됩니다.
#   \n 은 "줄바꿈"을 뜻하는 특수 문자입니다. 줄 맨 앞의 ## 만 정확히 잡으려고 넣습니다.
#
#   즉:  raw.split(???)
# ===========================================================================

sections = raw.split("\n##")  # ← 여기를 채우세요


# ===========================================================================
# 여기부터는 결과 출력용입니다. 고치지 않아도 됩니다.
# ===========================================================================

def main() -> None:
    if raw is None:
        print("TODO 1 이 비어 있습니다. raw 를 채우세요.")
        return

    print(f"\n문서: {DOC_PATH.name}")
    print(f"전체 길이: {len(raw)}자")
    print(f"\n--- 앞부분 120자 미리보기 ---\n{raw[:120]}...\n")

    if sections is None:
        print("TODO 2 가 비어 있습니다. sections 를 채우세요.")
        return

    print("=" * 58)
    print(f"{len(sections)}개 조각으로 잘렸습니다.")
    print("=" * 58)

    for i, sec in enumerate(sections):
        # 각 조각의 첫 줄을 제목으로 삼는다 (splitlines 는 줄 단위로 쪼갠다)
        first_line = sec.strip().splitlines()[0] if sec.strip() else "(빈 조각)"
        print(f"\n[{i}] {len(sec):4d}자   {first_line}")
        preview = " ".join(sec.strip().split())[:70]
        print(f"      {preview}...")

    lengths = [len(s) for s in sections]
    print("\n" + "-" * 58)
    print(f"조각 길이: 최소 {min(lengths)}자 / 평균 {sum(lengths) // len(lengths)}자 / 최대 {max(lengths)}자")
    print("-" * 58)
    print("\n0번 조각이 좀 이상하게 느껴진다면, 그게 맞습니다.")
    print("왜 그런지 아래 '생각해볼 것'을 읽어보세요.")


# ===========================================================================
# 생각해볼 것 (코드 수정 없이 눈으로만)
#
#   1. 0번 조각에는 왜 '## ' 가 안 보일까요?
#      → split 은 기준 글자를 **먹어치웁니다**. "a-b".split("-") 는 ["a","b"] 이지
#         ["a","-b"] 가 아닙니다. 그래서 1번 조각부터는 제목만 남고 ## 가 사라졌고,
#         0번은 첫 ## 앞에 있던 문서 제목 부분이 통째로 남았습니다.
#
#   2. 이 방식의 한계는?
#      → 섹션 하나가 아주 길면 (예: 3000자) 그대로 거대한 청크가 됩니다.
#         실무에서는 "너무 긴 조각은 다시 자르기"를 한 겹 더 얹습니다.
#         그때 앞 조각의 끝부분을 다음 조각 앞에 겹쳐 넣는 걸 overlap 이라고 합니다.
#         문장이 경계에서 잘려 문맥을 잃는 걸 막기 위한 장치입니다.
#
#   3. 실험해보기
#      → DOC_PATH 를 다른 문서로 바꿔보세요.
#         "02-경비정산.md", "03-개발프로세스.md", "04-보안규정.md"
# ===========================================================================


if __name__ == "__main__":
    main()
